'use strict';
// Keep the cloud renderer byte-identical to the browser renderer. Run after
// changing kinetic-renderer.js and rebuild/push the Cog image before release.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const bytes = fs.readFileSync(path.join(root, 'kinetic-renderer.js'));
const version = crypto.createHash('sha256').update(bytes).digest('hex');
const target = path.join(root, 'cloud', 'replicate');
fs.mkdirSync(target, { recursive: true });
fs.writeFileSync(path.join(target, 'kinetic-renderer.js'), bytes);
fs.writeFileSync(path.join(target, 'renderer-version.txt'), version + '\n');
fs.writeFileSync(path.join(root, 'cloud-renderer-version.js'),
  `/* Generated by scripts/prepare-replicate.cjs. */\nglobalThis.JAW_RENDERER_VERSION = '${version}';\n`);
console.log('Prepared JAA Replicate renderer ' + version);
